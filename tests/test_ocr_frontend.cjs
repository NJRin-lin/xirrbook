const assert = require('node:assert/strict');
const {keyOf, issues, applyReview, needsReview, resolveDuplicates, escapeHTML} = require('../frontend/ocr.js');
const row = updates => ({date:'2025-01-01',symbol:'易方达蓝筹精选',business_type:'买入',cash_flow:1000,decision:'keep',...updates});
const result = (index, db = [], batch = []) => ({index,errors:[],database_ids:db,batch_indexes:batch});
assert.equal(issues(row()).length,0);
assert.ok(issues(row({date:'2025-02-30'})).length);
assert.ok(issues(row({cash_flow:null})).length);
assert.equal(issues(row({business_type:'当前市值',market_value:0})).length,0);
assert.equal(keyOf(row({cash_flow:1000})),keyOf(row({cash_flow:1000.00})));
const rows = [row(),row(),row({cash_flow:2000})];
applyReview(rows,[result(0,[],[1]),result(1,[],[0]),result(2)]);
assert.equal(rows[0].decision,'review');
assert.equal(rows[1].decision,'review');
assert.equal(rows[2].decision,'keep');
assert.ok(needsReview(rows[0]));
resolveDuplicates(rows);
assert.deepEqual(rows.map(r=>r.decision),['keep','skip','keep']);
applyReview(rows,[result(0,[],[1]),result(1,[],[0]),result(2)]);
assert.deepEqual(rows.map(r=>r.decision),['keep','skip','keep']);
rows[0].cash_flow=3000;
applyReview(rows,[result(0,[10]),result(1),result(2)]);
assert.equal(rows[0].decision,'review');
assert.equal(rows[0].allow_duplicate,false);
const existing=[row()];
applyReview(existing,[result(0,[1])]);
resolveDuplicates(existing);
assert.equal(existing[0].decision,'skip');
const manual=[row()];
applyReview(manual,[result(0)]);
applyReview(manual,[result(0,[99])]);
assert.equal(manual[0].decision,'review');
assert.equal(escapeHTML('<img src=x onerror="alert(1)">'),'&lt;img src=x onerror=&quot;alert(1)&quot;&gt;');
console.log('OCR frontend review checks passed: validation, explicit duplicate choices, edits invalidate approval, late database duplicates, safe text.');
